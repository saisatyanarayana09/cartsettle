class Command(BaseCommand):
    help = 'Cleans old catalog and seeds exactly 100 authentic packaged products on pure white backgrounds across 12 categories'

    def handle(self, *args, **kwargs):
        self.stdout.write("Starting complete cleanup and 100-packet catalog seeding...")

        # 1. Clear cart items and favorites to avoid foreign key cascades
        CartItem.objects.all().delete()
        Favorite.objects.all().delete()
        self.stdout.write("Cleared CartItems and Favorites.")

        # 2. Delete all existing products cleanly
        deleted_count, _ = Product.objects.all().delete()
        self.stdout.write(f"Deleted {deleted_count} existing products.")

        # 3. Clean up legacy categories not in the 12 canonical list
        canonical_names = [c['name'] for c in CATEGORIES_DATA]
        Category.objects.exclude(name__in=canonical_names).delete()
        self.stdout.write("Cleaned up legacy/dummy categories.")

        # 4. Create or update the 12 canonical categories
        cat_map = {}
        for cdata in CATEGORIES_DATA:
            cat, created = Category.objects.update_or_create(
                name=cdata['name'],
                defaults={
                    'slug': slugify(cdata['name']),
                    'display_order': cdata['display_order'],
                    'image': cdata['image'],
                    'is_active': True
                }
            )
            cat_map[cdata['name']] = cat
            status_str = "Created" if created else "Updated"
            self.stdout.write(f"  [Category] {status_str}: {cat.name}")

        # 5. Seed the exactly 100 authentic packaged products
        created_prods = 0
        for i, pdata in enumerate(PRODUCTS_100_DATA):
            cat = cat_map.get(pdata['category'])
            prod = Product.objects.create(
                category=cat,
                name=pdata['name'],
                brand=pdata.get('brand', ''),
                unit=pdata['unit'],
                regular_price=pdata['regular_price'],
                offer_price=pdata.get('offer_price'),
                cost_price=pdata.get('cost_price'),
                stock_quantity=pdata.get('stock_quantity', 50),
                sku=pdata.get('sku', f"SKU-{1000 + i}"),
                description=pdata.get('description', ''),
                image=pdata.get('image', ''),
                tags=pdata.get('tags'),
                display_order=i,
                is_active=True,
                is_in_stock=True
            )
            created_prods += 1

        self.stdout.write(self.style.SUCCESS(f"Successfully created {created_prods} authentic packaged products across {len(cat_map)} categories!"))

        # 6. Invalidate caches
        cache.delete('active_categories_serialized')
        cache.delete('categories_all_cached')
        self.stdout.write(self.style.SUCCESS("Caches cleared. 100-packet catalog ready!"))

        # 7. Ensure canonical Demo Login accounts ('owner' and 'shopper') exist and are active
        from django.contrib.auth import get_user_model
        User = get_user_model()
        owner_u, _ = User.objects.get_or_create(
            username='owner',
            defaults={
                'email': 'owner@cartsettle.store',
                'first_name': 'Store',
                'last_name': 'Owner',
                'is_active': True,
                'is_owner': True,
                'is_staff': True,
            }
        )
        owner_u.is_active = True
        owner_u.is_owner = True
        owner_u.is_staff = True
        owner_u.set_password('CartSettle@2026')
        owner_u.save()

        shopper_u, _ = User.objects.get_or_create(
            username='shopper',
            defaults={
                'email': 'shopper@cartsettle.store',
                'first_name': 'Demo',
                'last_name': 'Shopper',
                'is_active': True,
            }
        )
        shopper_u.is_active = True
        shopper_u.set_password('Shopper@2026')
        shopper_u.save()
        self.stdout.write(self.style.SUCCESS("Verified Demo Login accounts: 'owner' and 'shopper'."))

        # 8. Automatically populate the 5 meaningful showcase sections
        from django.core.management import call_command
        try:
            call_command('seed_showcase_sections')
        except Exception as e:
            self.stdout.write(self.style.WARNING(f"Could not automatically seed showcase sections: {e}"))
